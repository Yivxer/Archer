#!/usr/bin/env python3
"""Generate platform token files from the shared Archer CSS tokens."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "client/desktop/src/renderer/src/tokens.css"
DEFAULT_JSON = ROOT / "web/public/assets/generated/tokens.json"
DEFAULT_TS = ROOT / "client/desktop/src/renderer/src/generated/tokens.ts"


def parse_tokens(css: str) -> dict:
    root_tokens = _tokens_for_selector(css, r":root")
    dark_overrides = _tokens_for_selector(css, r":root\[data-theme=\"dark\"\]")
    if not root_tokens:
        raise ValueError("no :root CSS custom properties found")
    return {
        "themes": {
            "light": root_tokens,
            "dark": {**root_tokens, **dark_overrides},
        },
        "overrides": {
            "dark": dark_overrides,
        },
    }


def build_payload(source: Path) -> dict:
    parsed = parse_tokens(source.read_text(encoding="utf-8"))
    return {
        "source": source.relative_to(ROOT).as_posix() if source.is_relative_to(ROOT) else str(source),
        **parsed,
    }


def render_json(payload: dict) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def render_ts(payload: dict) -> str:
    json_payload = json.dumps(payload, ensure_ascii=False, indent=2)
    return (
        "/* Generated by scripts/generate_tokens.py. Do not edit by hand. */\n"
        f"export const designTokens = {json_payload} as const\n\n"
        "export type DesignTokenTheme = keyof typeof designTokens.themes\n"
        "export type DesignTokenName = keyof typeof designTokens.themes.light\n"
    )


def write_outputs(source: Path, json_path: Path, ts_path: Path) -> None:
    payload = build_payload(source)
    _write(json_path, render_json(payload))
    _write(ts_path, render_ts(payload))


def check_outputs(source: Path, json_path: Path, ts_path: Path) -> bool:
    payload = build_payload(source)
    expected = {
        json_path: render_json(payload),
        ts_path: render_ts(payload),
    }
    ok = True
    for path, content in expected.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != content:
            print(f"out of sync: {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}", file=sys.stderr)
            ok = False
    return ok


def _tokens_for_selector(css: str, selector: str) -> dict[str, str]:
    pattern = re.compile(selector + r"\s*\{(?P<body>.*?)\}", re.DOTALL)
    tokens: dict[str, str] = {}
    for match in pattern.finditer(css):
        body = match.group("body")
        for name, value in re.findall(r"--([A-Za-z0-9_-]+)\s*:\s*([^;]+);", body):
            tokens[name] = re.sub(r"\s+", " ", value.strip())
    return tokens


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--json", type=Path, default=DEFAULT_JSON)
    parser.add_argument("--ts", type=Path, default=DEFAULT_TS)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    source = args.source.expanduser()
    json_path = args.json.expanduser()
    ts_path = args.ts.expanduser()
    if args.check:
        return 0 if check_outputs(source, json_path, ts_path) else 1
    write_outputs(source, json_path, ts_path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
